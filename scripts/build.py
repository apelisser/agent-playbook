#!/usr/bin/env python3
"""Compile rules/, skills/ and agents/ into dist/AGENTS.md.

dist/AGENTS.md is the single global-instructions file for tools that read one
Markdown file (Claude Code CLAUDE.md, Codex AGENTS.md, Gemini GEMINI.md, Copilot,
pasted system prompts). Tools with native rules/skills (Cursor) use the sources.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n?", re.S)


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    match = FRONTMATTER.match(text)
    if not match:
        return {}, text
    meta: dict[str, str] = {}
    for line in match.group(1).splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            meta[key.strip()] = value.strip().strip('"')
    return meta, text[match.end():]


def repo_path(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def demote_headings(body: str, levels: int = 2) -> str:
    out, fenced = [], False
    for line in body.splitlines():
        if line.startswith("```"):
            fenced = not fenced
        if not fenced and line.startswith("#"):
            line = "#" * levels + line
        out.append(line)
    return "\n".join(out).strip()


def main() -> int:
    always, scoped = [], []
    for path in sorted((ROOT / "rules").glob("*.md")):
        meta, body = split_frontmatter(path.read_text())
        if meta.get("alwaysApply") == "true":
            always.append((path, meta, demote_headings(body)))
        else:
            scoped.append((path, meta, demote_headings(body, 3)))

    parts = [
        "# Global agent instructions",
        "",
        "<!-- Generated by scripts/build.py from rules/, skills/ and agents/. Do not edit. -->",
        "",
        "`AGENTS.md` and `docs/agente/` of the current repository override everything below.",
        "",
        "## Always",
    ]
    for path, _, body in always:
        parts += ["", f"<!-- rules/{path.name} -->", body]

    if scoped:
        parts += ["", "## By file type"]
        for path, meta, body in scoped:
            parts += ["", f"### When editing `{meta.get('globs', '*')}`", "", body]

    parts += [
        "",
        "## Skills",
        "",
        "Load a skill only when its description matches the task: read the file, then follow it. Paths are relative to the playbook root. The installer links that root at `~/.agent-playbook/`; without installation, the user must provide access to the source checkout.",
        "",
    ]
    for skill in sorted((ROOT / "skills").glob("*/SKILL.md")):
        meta, _ = split_frontmatter(skill.read_text())
        parts.append(f"- `{meta['name']}` ({repo_path(skill)}): {meta['description']}")

    parts += [
        "",
        "## Subagents",
        "",
        "If the tool supports subagents, delegate to these when useful. Otherwise read the file from the playbook root and apply it as a review lens.",
        "",
    ]
    for agent in sorted((ROOT / "agents").glob("*.md")):
        meta, _ = split_frontmatter(agent.read_text())
        parts.append(f"- `{meta['name']}` ({repo_path(agent)}): {meta['description']}")

    out = "\n".join(parts) + "\n"
    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    (dist / "AGENTS.md").write_text(out)
    codex_agents = dist / "codex" / "agents"
    codex_agents.mkdir(parents=True, exist_ok=True)
    source_agents = sorted((ROOT / "agents").glob("*.md"))
    expected = {f"{agent.stem}.toml" for agent in source_agents}
    for stale in codex_agents.glob("*.toml"):
        if stale.name not in expected:
            stale.unlink()
    for agent in source_agents:
        meta, body = split_frontmatter(agent.read_text())
        content = "\n".join(
            f"{key} = {json.dumps(value, ensure_ascii=False)}"
            for key, value in (
                ("name", meta["name"]),
                ("description", meta["description"]),
                ("developer_instructions", body.strip()),
            )
        ) + "\n"
        (codex_agents / f"{agent.stem}.toml").write_text(content)
    print(f"wrote {dist / 'AGENTS.md'} ({len(out.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
